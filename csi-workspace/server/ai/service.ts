/**
 * AI service layer.
 *
 * - Provider: Anthropic Claude (official SDK) when ANTHROPIC_API_KEY is set AND the
 *   admin setting `ai.enabled` is true.
 * - Fallback: a deterministic rule-based engine. It is always labelled as "rules" in the UI
 *   and never presented as AI.
 *
 * Every output from this module is a *suggestion*. Callers store results in `ai_suggestions`
 * or as drafts; nothing becomes an authoritative record without a human accepting it.
 */
import Anthropic from "@anthropic-ai/sdk";
import { z } from "zod";
import type { AppContext } from "../lib/context.js";
import { getSetting } from "../lib/events.js";
import { newId, nowIso, addDays } from "../lib/ids.js";

export type Engine = { kind: "anthropic"; model: string; client: Anthropic } | { kind: "rules" };

export function aiEnabledSetting(ctx: AppContext) {
  return getSetting(ctx.db, "ai.enabled", true);
}

export function engine(ctx: AppContext): Engine {
  if (ctx.config.anthropicApiKey && aiEnabledSetting(ctx)) {
    return { kind: "anthropic", model: ctx.config.aiModel, client: new Anthropic({ apiKey: ctx.config.anthropicApiKey }) };
  }
  return { kind: "rules" };
}
export const engineLabel = (e: Engine) => (e.kind === "anthropic" ? `anthropic:${e.model}` : "rules");

export function aiStatus(ctx: AppContext) {
  const e = engine(ctx);
  return {
    engine: engineLabel(e),
    aiAvailable: e.kind === "anthropic",
    configured: !!ctx.config.anthropicApiKey,
    enabledSetting: aiEnabledSetting(ctx),
    note:
      e.kind === "anthropic"
        ? "AI suggestions are generated by Claude and must be reviewed before they take effect."
        : "AI is not configured. Suggestions come from a rule-based extractor that looks for explicit markers (Action:, Decision:, Risk:, “X to …”).",
  };
}

function logUsage(ctx: AppContext, userId: string | null, feature: string, eng: string, usage: { input_tokens?: number; output_tokens?: number } | null, error = "") {
  ctx.db.insert("ai_usage", {
    id: newId("aiu"),
    user_id: userId,
    feature,
    engine: eng,
    input_tokens: usage?.input_tokens ?? null,
    output_tokens: usage?.output_tokens ?? null,
    ok: error ? 0 : 1,
    error: error.slice(0, 500),
    created_at: nowIso(),
  });
}

// ===================================================================== meeting analysis
export const MeetingAnalysisSchema = z.object({
  summary: z.string(),
  key_topics: z.array(z.string()),
  decisions: z.array(z.object({ title: z.string(), detail: z.string(), evidence: z.string(), confidence: z.enum(["high", "medium", "low"]) })),
  actions: z.array(
    z.object({
      title: z.string(),
      detail: z.string(),
      owner_name: z.string().describe("Exact participant name only if the notes explicitly assign this person; otherwise empty string"),
      due_date: z.string().describe("YYYY-MM-DD only if a deadline is explicitly stated; otherwise empty string"),
      due_date_basis: z.string().describe("Quote of the text that states the deadline, or empty"),
      evidence: z.string().describe("Verbatim quote from the notes supporting this action"),
      confidence: z.enum(["high", "medium", "low"]),
    }),
  ),
  risks: z.array(z.object({ title: z.string(), detail: z.string(), kind: z.enum(["risk", "blocker"]), evidence: z.string(), confidence: z.enum(["high", "medium", "low"]) })),
  follow_up_questions: z.array(z.string()),
  project_update: z.string().describe("Short factual project update drawn only from the notes, or empty"),
  knowledge_items: z.array(z.object({ title: z.string(), insight: z.string(), evidence: z.string() })),
});
export type MeetingAnalysis = z.infer<typeof MeetingAnalysisSchema>;

export interface MeetingInput {
  title: string;
  date: string;
  projectName?: string | null;
  participants: { id: string | null; name: string }[];
  notes: string;
  transcript?: string;
}

const MEETING_SYSTEM = `You analyse meeting notes for Change Science Institute (CSI), producing suggestions that a human meeting owner will review.
Strict rules:
- Use only what the notes/transcript say. Never invent decisions, deadlines, owners or outcomes.
- An action is something someone explicitly agreed or was asked to do. Do not turn every statement or idea into an action.
- Set owner_name only when the text clearly names who will do it, using the participant's name as listed. Otherwise leave it empty.
- Set due_date only when a deadline is explicitly stated. Resolve relative dates ("by Friday") against the meeting date and quote the basis. Otherwise leave it empty.
- A decision must be stated as decided/agreed/approved. Proposals, options and speculation are not decisions.
- Every decision, action and risk must include a short verbatim evidence quote.
- Mark confidence "low" when the wording is ambiguous.
- Keep the summary factual, neutral and concise (3–6 sentences).`;

export async function analyseMeeting(ctx: AppContext, userId: string | null, input: MeetingInput): Promise<{ engine: string; analysis: MeetingAnalysis }> {
  const e = engine(ctx);
  if (e.kind === "anthropic") {
    try {
      const content = [
        `Meeting: ${input.title}`,
        `Date: ${input.date}`,
        input.projectName ? `Project: ${input.projectName}` : "",
        `Participants: ${input.participants.map((p) => p.name).join(", ") || "(not recorded)"}`,
        "",
        "<notes>",
        input.notes,
        "</notes>",
        input.transcript ? `\n<transcript>\n${input.transcript}\n</transcript>` : "",
      ].join("\n");
      const r = await e.client.messages
        .stream({
          model: e.model,
          max_tokens: 32000,
          system: MEETING_SYSTEM,
          output_config: { effort: "medium", format: jsonSchemaFormat(MeetingAnalysisSchema) },
          messages: [{ role: "user", content }],
        })
        .finalMessage();
      logUsage(ctx, userId, "meeting_analysis", engineLabel(e), r.usage);
      const analysis = parseStructured(r, MeetingAnalysisSchema);
      return { engine: engineLabel(e), analysis };
    } catch (err) {
      logUsage(ctx, userId, "meeting_analysis", engineLabel(e), null, String(err));
      console.error("[ai] meeting analysis failed, using rules", err);
      // fall through to rules, clearly labelled
    }
  }
  logUsage(ctx, userId, "meeting_analysis", "rules", null);
  return { engine: "rules", analysis: ruleBasedMeeting(input) };
}

/** Read a structured-output response: check stop reason, JSON-parse the text, validate with zod. */
function parseStructured<T extends z.ZodTypeAny>(msg: Anthropic.Message, schema: T): z.infer<T> {
  if (msg.stop_reason === "refusal") throw new Error("model declined the request");
  if (msg.stop_reason === "max_tokens") throw new Error("output truncated (max_tokens)");
  const text = msg.content.filter((b): b is Anthropic.TextBlock => b.type === "text").map((b) => b.text).join("");
  return schema.parse(JSON.parse(text));
}

/** Build an output_config.format JSON schema from a zod schema (no extra dependency). */
function jsonSchemaFormat(schema: z.ZodTypeAny): Anthropic.JSONOutputFormat {
  return { type: "json_schema", schema: zodToJsonSchema(schema) };
}
function zodToJsonSchema(s: z.ZodTypeAny): Record<string, unknown> {
  const desc = s.description ? { description: s.description } : {};
  if (s instanceof z.ZodObject) {
    const shape = s.shape as Record<string, z.ZodTypeAny>;
    const props: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(shape)) props[k] = zodToJsonSchema(v);
    return { type: "object", properties: props, required: Object.keys(shape), additionalProperties: false, ...desc };
  }
  if (s instanceof z.ZodArray) return { type: "array", items: zodToJsonSchema(s.element), ...desc };
  if (s instanceof z.ZodEnum) return { type: "string", enum: s.options, ...desc };
  if (s instanceof z.ZodNumber) return { type: "number", ...desc };
  if (s instanceof z.ZodBoolean) return { type: "boolean", ...desc };
  return { type: "string", ...desc };
}

// ---------------------------------------------------------------- rule-based extractor
const WEEKDAYS = ["sunday", "monday", "tuesday", "wednesday", "thursday", "friday", "saturday"];
const MONTHS = ["january", "february", "march", "april", "may", "june", "july", "august", "september", "october", "november", "december"];

export function extractDeadline(text: string, meetingDate: string): { date: string; basis: string } | null {
  const iso = text.match(/\b(\d{4}-\d{2}-\d{2})\b/);
  if (iso) return { date: iso[1], basis: iso[0] };
  const dm = text.match(/\b(?:by|before|due|on)\s+(?:the\s+)?(\d{1,2})(?:st|nd|rd|th)?\s+(january|february|march|april|may|june|july|august|september|october|november|december)\b(?:\s+(\d{4}))?/i);
  if (dm) {
    const year = dm[3] ? parseInt(dm[3], 10) : parseInt(meetingDate.slice(0, 4), 10);
    const m = MONTHS.indexOf(dm[2].toLowerCase()) + 1;
    let date = `${year}-${String(m).padStart(2, "0")}-${String(parseInt(dm[1], 10)).padStart(2, "0")}`;
    if (!dm[3] && date < meetingDate) date = `${year + 1}${date.slice(4)}`;
    return { date, basis: dm[0] };
  }
  const wd = text.match(/\b(?:by|before|on|due)\s+(?:next\s+)?(monday|tuesday|wednesday|thursday|friday|saturday|sunday)\b/i);
  if (wd) {
    const target = WEEKDAYS.indexOf(wd[1].toLowerCase());
    const cur = new Date(meetingDate + "T00:00:00Z").getUTCDay();
    let delta = (target - cur + 7) % 7;
    if (delta === 0) delta = 7;
    if (/next/i.test(wd[0]) && delta < 7) delta += 7;
    return { date: addDays(meetingDate, delta), basis: wd[0] };
  }
  if (/\b(?:by\s+)?end of (?:the )?week\b/i.test(text)) {
    const cur = new Date(meetingDate + "T00:00:00Z").getUTCDay();
    const delta = (5 - cur + 7) % 7 || 7;
    return { date: addDays(meetingDate, delta), basis: "end of week" };
  }
  return null;
}

function cleanLine(l: string) {
  return l.replace(/^\s*(?:[-*•]|\d+[.)]|\[ ?\]|\[x\])\s*/i, "").trim();
}

export function ruleBasedMeeting(input: MeetingInput): MeetingAnalysis {
  const text = [input.notes, input.transcript ?? ""].join("\n");
  const lines = text.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  const names = input.participants.map((p) => p.name).filter(Boolean);
  const findOwner = (s: string): string => {
    for (const n of names) {
      const first = n.split(/\s+/)[0];
      const re = new RegExp(`^(?:${escapeRe(n)}|${escapeRe(first)})\\b`, "i");
      const inline = new RegExp(`\\((?:owner:\\s*)?(?:${escapeRe(n)}|${escapeRe(first)})\\)|owner:\\s*(?:${escapeRe(n)}|${escapeRe(first)})\\b|@(?:${escapeRe(first)})\\b`, "i");
      if (re.test(s) || inline.test(s)) return n;
    }
    return "";
  };
  const out: MeetingAnalysis = { summary: "", key_topics: [], decisions: [], actions: [], risks: [], follow_up_questions: [], project_update: "", knowledge_items: [] };
  let section: "" | "actions" | "decisions" | "risks" | "questions" | "topics" = "";
  for (const raw of lines) {
    const header = raw.replace(/[:#*]/g, "").trim().toLowerCase();
    if (/^(action items?|actions|next steps|to ?dos?)$/.test(header)) { section = "actions"; continue; }
    if (/^(decisions?( made)?|agreed|resolutions?)$/.test(header)) { section = "decisions"; continue; }
    if (/^(risks?|risks and blockers|blockers|issues|concerns)$/.test(header)) { section = "risks"; continue; }
    if (/^(questions|open questions|follow[- ]?ups?)$/.test(header)) { section = "questions"; continue; }
    if (/^(discussion|key (discussion )?points|agenda|topics)$/.test(header)) { section = "topics"; continue; }
    const line = cleanLine(raw);
    if (!line) continue;
    const lower = line.toLowerCase();

    const explicitAction = /^(action|ap|todo|to do|ai)\s*[:\-–]/i.test(line);
    const decisionMarker = /^(decision|decided|agreed)\s*[:\-–]/i.test(line) || /\b(we|the team|it was) (agreed|decided)\b/i.test(line) || /\bwas approved\b/i.test(line);
    const riskMarker = /^(risk|blocker|issue|concern)\s*[:\-–]/i.test(line);
    const owner = findOwner(line.replace(/^(action|ap|todo|to do|ai)\s*[:\-–]\s*/i, ""));
    const personCommit = !!owner && new RegExp(`^${escapeRe(owner.split(" ")[0])}[a-z ]*\\s+(to|will|agreed to|is to|has to|must)\\s+`, "i").test(line.replace(/^(action|ap|todo)\s*[:\-–]\s*/i, ""));

    if (decisionMarker || section === "decisions") {
      const title = line.replace(/^(decision|decided|agreed)\s*[:\-–]\s*/i, "");
      out.decisions.push({ title: truncate(title, 140), detail: title, evidence: raw, confidence: decisionMarker ? "high" : "medium" });
      continue;
    }
    if (riskMarker || section === "risks") {
      const kind = /^blocker/i.test(line) || /\bblock(ed|er|ing)\b/i.test(lower) ? "blocker" : "risk";
      const title = line.replace(/^(risk|blocker|issue|concern)\s*[:\-–]\s*/i, "");
      out.risks.push({ title: truncate(title, 140), detail: title, kind, evidence: raw, confidence: riskMarker ? "high" : "medium" });
      continue;
    }
    if (explicitAction || personCommit || section === "actions") {
      const title = line.replace(/^(action|ap|todo|to do|ai)\s*[:\-–]\s*/i, "").replace(/\s*\((?:owner:\s*)?[^)]*\)\s*$/i, "");
      const dl = extractDeadline(line, input.date);
      out.actions.push({
        title: truncate(stripOwnerPrefix(title, owner), 160),
        detail: title,
        owner_name: owner,
        due_date: dl?.date ?? "",
        due_date_basis: dl?.basis ?? "",
        evidence: raw,
        confidence: explicitAction || personCommit ? (owner ? "high" : "medium") : "low",
      });
      continue;
    }
    if (section === "questions" || /\?\s*$/.test(line)) {
      out.follow_up_questions.push(line);
      continue;
    }
    if (section === "topics" && line.length > 3) out.key_topics.push(truncate(line, 120));
    if (/^(insight|lesson|learning|learned)\s*[:\-–]/i.test(line)) {
      const t = line.replace(/^(insight|lesson|learning|learned)\s*[:\-–]\s*/i, "");
      out.knowledge_items.push({ title: truncate(t, 120), insight: t, evidence: raw });
    }
  }
  if (!out.key_topics.length) {
    out.key_topics = lines
      .filter((l) => /^#+\s|^[A-Z][^.!?]{3,60}:$/.test(l))
      .map((l) => l.replace(/^#+\s*|:$/g, ""))
      .slice(0, 6);
  }
  const parts = [
    `${input.title} (${input.date})${input.projectName ? ` for ${input.projectName}` : ""}.`,
    out.key_topics.length ? `Topics noted: ${out.key_topics.slice(0, 5).join("; ")}.` : "",
    `${out.decisions.length} decision(s), ${out.actions.length} action item(s) and ${out.risks.length} risk/blocker item(s) were identified from explicit markers in the notes.`,
  ];
  out.summary = parts.filter(Boolean).join(" ");
  if (out.actions.length || out.decisions.length) {
    out.project_update = [
      out.decisions.length ? `Decisions: ${out.decisions.map((d) => d.title).join("; ")}.` : "",
      out.actions.length ? `New actions: ${out.actions.length}.` : "",
    ].filter(Boolean).join(" ");
  }
  return out;
}

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const truncate = (s: string, n: number) => (s.length > n ? s.slice(0, n - 1).trimEnd() + "…" : s);
function stripOwnerPrefix(title: string, owner: string) {
  if (!owner) return title;
  const first = owner.split(" ")[0];
  const t = title.replace(new RegExp(`^(?:${escapeRe(owner)}|${escapeRe(first)})\\s+(?:to|will|agreed to|is to|has to|must)\\s+`, "i"), "");
  return t.charAt(0).toUpperCase() + t.slice(1);
}

// ===================================================================== generic drafting
/**
 * Draft prose from supplied facts (e.g. Fakawe executive overview). Returns null when AI is
 * unavailable so callers can use a template instead — we never fake an AI draft.
 */
export async function draftFromFacts(
  ctx: AppContext,
  userId: string | null,
  feature: string,
  instruction: string,
  facts: string,
): Promise<{ engine: string; text: string } | null> {
  const e = engine(ctx);
  if (e.kind !== "anthropic") return null;
  try {
    const r = await e.client.messages.create({
      model: e.model,
      max_tokens: 4000,
      system:
        "You write concise, factual internal reporting text for Change Science Institute. Use only the facts provided. Do not exaggerate progress, invent accomplishments, or present plans as completed work. Distinguish decisions from proposals. If information is missing, say so briefly. Plain prose, no markdown headings.",
      output_config: { effort: "low" },
      messages: [{ role: "user", content: `${instruction}\n\n<facts>\n${facts}\n</facts>` }],
    });
    logUsage(ctx, userId, feature, engineLabel(e), r.usage);
    if (r.stop_reason === "refusal") return null;
    const text = r.content.filter((b): b is Anthropic.TextBlock => b.type === "text").map((b) => b.text).join("\n").trim();
    return text ? { engine: engineLabel(e), text } : null;
  } catch (err) {
    logUsage(ctx, userId, feature, engineLabel(e), null, String(err));
    console.error("[ai] draft failed", err);
    return null;
  }
}

// ===================================================================== knowledge Q&A
export interface KnowledgeSource {
  id: string;
  title: string;
  category: string;
  summary: string;
  body: string;
  link: string;
}

/**
 * Answer a question using ONLY the supplied (already permission-filtered) sources.
 * Without AI, returns null and the caller shows ranked search results instead.
 */
export async function answerFromSources(
  ctx: AppContext,
  userId: string | null,
  question: string,
  sources: KnowledgeSource[],
): Promise<{ engine: string; answer: string; cited: string[]; insufficient: boolean } | null> {
  const e = engine(ctx);
  if (e.kind !== "anthropic" || !sources.length) return null;
  const Schema = z.object({
    answer: z.string(),
    cited_source_ids: z.array(z.string()),
    insufficient_information: z.boolean(),
  });
  try {
    const docs = sources
      .map((s) => `<source id="${s.id}" title="${s.title.replace(/"/g, "'")}" category="${s.category}">\n${s.summary}\n${s.body.slice(0, 6000)}\n</source>`)
      .join("\n");
    const r = await e.client.messages.create({
      model: e.model,
      max_tokens: 8000,
      system:
        "You answer questions for CSI staff using only the provided internal sources. Cite source ids you relied on. If the sources do not contain the answer, say so plainly and set insufficient_information=true. Distinguish facts stated in sources from your interpretation (prefix interpretation with 'Interpretation:'). Never invent internal facts, people, dates or decisions.",
      output_config: { effort: "low", format: jsonSchemaFormat(Schema) },
      messages: [{ role: "user", content: `${docs}\n\nQuestion: ${question}` }],
    });
    logUsage(ctx, userId, "knowledge_answer", engineLabel(e), r.usage);
    const out = parseStructured(r, Schema);
    const valid = new Set(sources.map((s) => s.id));
    return {
      engine: engineLabel(e),
      answer: out.answer,
      cited: out.cited_source_ids.filter((id) => valid.has(id)),
      insufficient: out.insufficient_information,
    };
  } catch (err) {
    logUsage(ctx, userId, "knowledge_answer", engineLabel(e), null, String(err));
    console.error("[ai] knowledge answer failed", err);
    return null;
  }
}
