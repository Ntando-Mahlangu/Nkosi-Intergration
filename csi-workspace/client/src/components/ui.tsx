// ------------------------------------------------------------------ buttons
type BtnVariant = "primary" | "secondary" | "ghost" | "danger" | "ai";
export function Button({
  variant = "secondary",
  size,
  loading,
  icon,
  children,
  className = "",
  type = "button",
  ...rest
}: React.ButtonHTMLAttributes<HTMLButtonElement> & { variant?: BtnVariant; size?: "sm"; loading?: boolean; icon?: string }) {
  const v = variant === "secondary" ? "" : `btn-${variant}`;
  return (
    <button type={type} className={`btn ${v} ${size === "sm" ? "btn-sm" : ""} ${className}`} disabled={loading || rest.disabled} aria-busy={loading || undefined} {...rest}>
      {loading ? <span className="spinner" aria-hidden /> : icon ? <Icon name={icon} size={16} /> : null}
      {children}
    </button>
  );
}

export function LinkButton({ to, variant = "secondary", size, icon, children }: { to: string; variant?: BtnVariant; size?: "sm"; icon?: string; children: React.ReactNode }) {
  const v = variant === "secondary" ? "" : `btn-${variant}`;
  return (
    <Link to={to} className={`btn ${v} ${size === "sm" ? "btn-sm" : ""}`}>
      {icon && <Icon name={icon} size={16} />}
      {children}
    </Link>
  );
}

// ------------------------------------------------------------------ badges
export function Badge({ tone = "neutral", icon, children, title }: { tone?: Tone; icon?: string; children: React.ReactNode; title?: string }) {
  return (
    <span className={`badge tone-${tone}`} title={title}>
      {icon && <Icon name={icon} size={12} />}
      {children}
    </span>
  );
}

/** Status badge for any entity kind defined in lib/status.ts (task, project, health, meeting, report...). */
export function StatusBadge({ kind, value }: { kind: string; value?: string | null }) {
  const s = statusMeta(kind, value);
  return (
    <Badge tone={s.tone} icon={s.icon}>
      {s.label}
    </Badge>
  );
}

export function PriorityBadge({ value }: { value?: string | null }) {
  if (!value || value === "normal") return null;
  return <StatusBadge kind="priority" value={value} />;
}

/** Marks AI-generated or rule-based content. Never omit this on generated output. */
export function AIBadge({ engine }: { engine?: string | null }) {
  const isAI = !!engine && engine.startsWith("anthropic");
  return (
    <Badge tone="ai" icon="sparkles" title={isAI ? `Generated by ${engine?.replace("anthropic:", "")} — review before relying on it` : "Generated by rule-based extraction (no AI) — review before relying on it"}>
      {isAI ? "AI suggestion" : "Rule-based suggestion"}
    </Badge>
  );
}

export function Tags({ value }: { value?: string | null }) {
  const tags = (value ?? "").split(",").map((t) => t.trim()).filter(Boolean);
  if (!tags.length) return null;
  return (
    <span className="row" style={{ gap: 4 }}>
      {tags.map((t) => (
        <span className="tag" key={t}>
          {t}
        </span>
      ))}
    </span>
  );
}

// ------------------------------------------------------------------ layout pieces
export function PageHeader({
  title,
  subtitle,
  actions,
  breadcrumbs,
}: {
  title: React.ReactNode;
  subtitle?: React.ReactNode;
  actions?: React.ReactNode;
  breadcrumbs?: { label: string; to?: string }[];
}) {
  return (
    <div className="page-header">
      <div style={{ minWidth: 0 }}>
        {breadcrumbs && breadcrumbs.length > 0 && (
          <nav className="breadcrumbs" aria-label="Breadcrumb">
            {breadcrumbs.map((b, i) => (
              <React.Fragment key={i}>
                {i > 0 && <Icon name="chevronRight" size={12} />}
                {b.to ? <Link to={b.to}>{b.label}</Link> : <span aria-current="page">{b.label}</span>}
              </React.Fragment>
            ))}
          </nav>
        )}
        <h1>{title}</h1>
        {subtitle && <div className="subtitle">{subtitle}</div>}
      </div>
      {actions && <div className="page-actions">{actions}</div>}
    </div>
  );
}

export function Card({ title, actions, children, className = "", pad = true, footer }: { title?: React.ReactNode; actions?: React.ReactNode; children: React.ReactNode; className?: string; pad?: boolean; footer?: React.ReactNode }) {
  return (
    <section className={`card ${className}`}>
      {(title || actions) && (
        <div className="card-header">
          {typeof title === "string" ? <h2>{title}</h2> : title}
          {actions && <div className="row">{actions}</div>}
        </div>
      )}
      <div className={pad ? "card-body" : ""}>{children}</div>
      {footer && <div className="card-footer">{footer}</div>}
    </section>
  );
}

export function StatCard({ label, value, hint, icon, tone, onClick, ariaLabel }: { label: string; value: React.ReactNode; hint?: React.ReactNode; icon?: string; tone?: Tone; onClick?: () => void; ariaLabel?: string }) {
  const inner = (
    <>
      <span className="stat-label">
        {icon && <Icon name={icon} size={16} />}
        {label}
      </span>
      <span className="stat-value">{value}</span>
      {hint && <span className="stat-hint">{hint}</span>}
    </>
  );
  return onClick ? (
    <button className={`stat-card ${tone ? `tone-${tone}` : ""}`} onClick={onClick} aria-label={ariaLabel}>
      {inner}
    </button>
  ) : (
    <div className={`card stat-card ${tone ? `tone-${tone}` : ""}`}>{inner}</div>
  );
}

export function ProgressBar({ value, label, tone }: { value: number | null | undefined; label?: string; tone?: Tone }) {
  const v = Math.max(0, Math.min(100, Math.round(value ?? 0)));
  return (
    <div className="stack-sm" style={{ gap: 4 }}>
      {label !== undefined && (
        <div className="row-between tiny muted">
          <span>{label}</span>
          <span>{value === null || value === undefined ? "—" : `${v}%`}</span>
        </div>
      )}
      <div className={`progress ${tone ? `tone-${tone}` : ""}`} role="progressbar" aria-valuenow={v} aria-valuemin={0} aria-valuemax={100} aria-label={label ?? "Progress"}>
        <span style={{ width: `${v}%` }} />
      </div>
    </div>
  );
}

const AVATAR_COLORS = ["#2557d6", "#6941c6", "#1f7a4d", "#9a5b00", "#b42318", "#0e7490", "#4f46e5", "#be185d"];
export function Avatar({ name, size }: { name?: string | null; size?: "sm" | "lg" }) {
  const n = name ?? "?";
  let h = 0;
  for (const c of n) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return (
    <span className={`avatar ${size ?? ""}`} style={{ background: AVATAR_COLORS[h % AVATAR_COLORS.length] }} title={n} aria-hidden>
      {initials(n)}
    </span>
  );
}

export function PersonChip({ name }: { name?: string | null }) {
  if (!name) return <span className="muted">Unassigned</span>;
  return (
    <span className="row" style={{ gap: 6 }}>
      <Avatar name={name} size="sm" />
      <span>{name}</span>
    </span>
  );
}

export function Tabs<T extends string>({ tabs, value, onChange }: { tabs: { key: T; label: string; count?: number }[]; value: T; onChange: (k: T) => void }) {
  return (
    <div className="tabs" role="tablist">
      {tabs.map((t) => (
        <button key={t.key} role="tab" aria-selected={value === t.key} className={`tab ${value === t.key ? "active" : ""}`} onClick={() => onChange(t.key)}>
          {t.label}
          {t.count !== undefined && <span className="count">{t.count}</span>}
        </button>
      ))}
    </div>
  );
}

export function Segmented<T extends string>({ options, value, onChange, label }: { options: { key: T; label: string; count?: number }[]; value: T; onChange: (k: T) => void; label?: string }) {
  return (
    <div className="segmented" role="group" aria-label={label}>
      {options.map((o) => (
        <button key={o.key} className={value === o.key ? "active" : ""} aria-pressed={value === o.key} onClick={() => onChange(o.key)}>
          {o.label}
          {o.count !== undefined && <span className="count">{o.count}</span>}
        </button>
      ))}
    </div>
  );
}

