export function ErrorState({ error, onRetry }: { error: ApiError | Error | string | null; onRetry?: () => void }) {
  if (!error) return null;
  const msg = typeof error === "string" ? error : error.message;
  const status = typeof error === "object" && "status" in error ? (error as ApiError).status : 0;
  return (
    <div className="empty" role="alert">
      <Icon name={status === 404 ? "search" : status === 403 ? "lock" : "alertCircle"} size={36} />
      <h3>{status === 404 ? "Not found" : status === 403 ? "Access restricted" : "Something went wrong"}</h3>
      <p>{msg}</p>
      {onRetry && status !== 404 && status !== 403 && (
        <Button onClick={onRetry} icon="refresh">
          Try again
        </Button>
      )}
    </div>
  );
}

